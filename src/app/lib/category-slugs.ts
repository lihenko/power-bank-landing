export const categoryIdsBySlug:
  Record<string, number> =
    Object.fromEntries(

      Object.entries(
        categorySlugs
      ).map(
        ([id, slug]) => [

          slug,

          Number(id),

        ]
      )

    );


/**
 * ============================================================
 * GET CATEGORY SLUG
 * ============================================================
 */

export function getCategorySlug(
  categoryId: number
): string | null {

  return (
    categorySlugs[
      categoryId
    ] ?? null
  );

}


/**
 * ============================================================
 * GET CATEGORY ID
 * ============================================================
 */

export function getCategoryIdBySlug(
  slug: string
): number | null {

  return (
    categoryIdsBySlug[
      slug
    ] ?? null
  );

}


