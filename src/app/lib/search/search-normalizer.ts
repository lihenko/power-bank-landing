/**
 * ============================================================
 * NORMALIZE TEXT
 * ============================================================
 */

function normalizeText(
  value: string
): string {

  return value
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ");

}


/**
 * ============================================================
 * GET SEARCH VARIANTS
 * ============================================================
 *
 * Повертає всі варіанти пошуку.
 *
 * ============================================================
 */

export function getSearchVariants(
  query: string
): string[] {

  const normalized =
    normalizeText(
      query
    );


  if (
    normalized.length === 0
  ) {

    return [];

  }


  const variants =
    new Set<string>();


  /*
   * ----------------------------------------------------------
   * Завжди додаємо оригінальний запит.
   * ----------------------------------------------------------
   */

  variants.add(
    normalized
  );


  /*
   * ----------------------------------------------------------
   * Якщо є прямий еквівалент.
   * ----------------------------------------------------------
   */

  const equivalents =
    SEARCH_EQUIVALENTS[
      normalized
    ];


  if (
    equivalents
  ) {

    for (
      const variant of equivalents
    ) {

      variants.add(
        normalizeText(
          variant
        )
      );

    }

  }


  /*
   * ----------------------------------------------------------
   * Якщо є словоформи.
   * ----------------------------------------------------------
   */

  const wordForms =
    SEARCH_WORD_FORMS[
      normalized
    ];


  if (
    wordForms
  ) {

    for (
      const variant of wordForms
    ) {

      variants.add(
        normalizeText(
          variant
        )
      );

    }

  }


  /*
   * ----------------------------------------------------------
   * Пошук еквівалентів через кожен варіант.
   *
   * Це потрібно, наприклад, коли:
   *
   * powerbank
   * ↓
   * повербанк
   * ↓
   * павербанк
   *
   * ----------------------------------------------------------
   */

  const currentVariants =
    Array.from(
      variants
    );


  for (
    const variant of currentVariants
  ) {

    const nestedEquivalents =
      SEARCH_EQUIVALENTS[
        variant
      ];


    if (
      nestedEquivalents
    ) {

      for (
        const nested of nestedEquivalents
      ) {

        variants.add(
          normalizeText(
            nested
          )
        );

      }

    }


    const nestedForms =
      SEARCH_WORD_FORMS[
        variant
      ];


    if (
      nestedForms
    ) {

      for (
        const nested of nestedForms
      ) {

        variants.add(
          normalizeText(
            nested
          )
        );

      }

    }

  }


  return Array.from(
    variants
  );

}


/**
 * ============================================================
 * EXPORT NORMALIZED QUERY
 * ============================================================
 */

export function normalizeSearchQuery(
  query: string
): string {

  return normalizeText(
    query
  );

}