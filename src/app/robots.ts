import { MetadataRoute } from "next";

export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      allow: "/",
      disallow: ["/api/", "/admin/"],
    },
    sitemap: "https://hitmarket.in.ua/sitemap.xml",
    host: "https://hitmarket.in.ua",
  };
}